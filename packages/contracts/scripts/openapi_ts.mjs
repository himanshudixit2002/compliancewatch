// Generates TypeScript types from the committed OpenAPI specs (make openapi-ts).
//
// For every packages/contracts/openapi/<service>.v<major>.json this writes
// clients/typescript/openapi/<service>.v<major>.d.ts with openapi-typescript's programmatic API
// and an index.ts that re-exports each file as a namespace and lists the services in
// OPENAPI_SERVICES. Stale files under the output directory are removed. Every output is run
// through prettier with the repository's configuration, so a regeneration is byte-for-byte
// stable and `pnpm format` never touches the files. The specs themselves are exported from the
// services (make openapi SERVICE=<name>); this script never edits them.
//
//   node scripts/openapi_ts.mjs          write the files
//   node scripts/openapi_ts.mjs --check  exit 1 when a committed file is missing, stale or differs
//
// The app imports the types type-only (`import type { profile } from
// "@compliancewatch/contracts/openapi"`), so nothing here is loaded at runtime.
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { format, resolveConfig } from "prettier";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const PACKAGE_DIR = resolve(SCRIPT_DIR, "..");
const REPO_ROOT = resolve(PACKAGE_DIR, "../..");
const SPEC_DIR = join(PACKAGE_DIR, "openapi");
const OUT_DIR = join(PACKAGE_DIR, "clients/typescript/openapi");
const SPEC_FILE = /^([a-z][a-z0-9-]*)\.v(\d+)\.json$/;
const HEADER = "// Generated by make openapi-ts from packages/contracts/openapi. Do not edit.";

// alphabetize: stable output regardless of the specs' key order (they are sorted anyway).
// exportType: `export type paths = ...` rather than interfaces, so the namespaces re-export cleanly.
// immutable: the app builds request bodies and reads responses as plain mutable objects.
// defaultNonNullable off: pydantic leaves a field with a default out of `required`, the services
// accept a request without it, and a Problem is serialised without its null fields; a property
// with a default is therefore optional in the request and in the response, not always present.
const OPTIONS = {
  alphabetize: true,
  exportType: true,
  immutable: false,
  defaultNonNullable: false,
};

/** "llm-gateway" -> "llmGateway": the namespace a spec is re-exported under. */
export function namespaceFor(service) {
  return service.replace(/-([a-z0-9])/g, (_, letter) => letter.toUpperCase());
}

/** The spec files, sorted by name: [{ service, major, file }]. */
export function listSpecs(specDir = SPEC_DIR) {
  return readdirSync(specDir)
    .map((name) => {
      const match = SPEC_FILE.exec(name);
      return match
        ? { service: match[1], major: Number(match[2]), file: join(specDir, name) }
        : null;
    })
    .filter((spec) => spec !== null)
    .sort((a, b) => a.service.localeCompare(b.service) || a.major - b.major);
}

async function prettify(source, fileName) {
  const options = (await resolveConfig(fileName)) ?? {};
  return format(source, { ...options, filepath: fileName });
}

/** The .d.ts for one spec, formatted. */
export async function renderSpec(spec) {
  const ast = await openapiTS(pathToFileURL(spec.file), OPTIONS);
  const outName = `${spec.service}.v${spec.major}.d.ts`;
  const source = `${HEADER}\n\n${astToString(ast)}`;
  return { name: outName, content: await prettify(source, join(OUT_DIR, outName)) };
}

/** index.ts: one namespace per spec plus the service list, formatted. */
export async function renderIndex(specs) {
  const lines = [HEADER, ""];
  for (const spec of specs) {
    lines.push(
      `export type * as ${namespaceFor(spec.service)} from "./${spec.service}.v${spec.major}";`,
    );
  }
  lines.push(
    "",
    "/** The services with a committed spec, named as their files under packages/contracts/openapi. */",
    `export const OPENAPI_SERVICES = [${specs.map((spec) => JSON.stringify(spec.service)).join(", ")}] as const;`,
    "",
    "export type OpenApiService = (typeof OPENAPI_SERVICES)[number];",
    "",
  );
  return { name: "index.ts", content: await prettify(lines.join("\n"), join(OUT_DIR, "index.ts")) };
}

/** Every file the output directory should contain. */
export async function renderAll(specs = listSpecs()) {
  const files = [];
  for (const spec of specs) files.push(await renderSpec(spec));
  files.push(await renderIndex(specs));
  return files;
}

function committedFiles() {
  if (!existsSync(OUT_DIR)) return [];
  return readdirSync(OUT_DIR).filter((name) => name === "index.ts" || name.endsWith(".d.ts"));
}

function relativeOut(name) {
  return join(OUT_DIR, name).slice(REPO_ROOT.length + 1);
}

export async function main(argv = process.argv.slice(2)) {
  const mode = argv[0] ?? "--write";
  if (mode !== "--write" && mode !== "--check") {
    console.error(`unknown option ${mode}; use --check or no option`);
    return 2;
  }
  const specs = listSpecs();
  if (specs.length === 0) {
    console.error(`no <service>.v<major>.json under ${SPEC_DIR}`);
    return 1;
  }
  const expected = await renderAll(specs);
  const expectedNames = new Set(expected.map((file) => file.name));
  const stale = committedFiles().filter((name) => !expectedNames.has(name));

  if (mode === "--check") {
    const problems = [];
    for (const file of expected) {
      const path = join(OUT_DIR, file.name);
      if (!existsSync(path)) problems.push(`${relativeOut(file.name)} is missing`);
      else if (readFileSync(path, "utf8") !== file.content) {
        problems.push(`${relativeOut(file.name)} differs from its spec`);
      }
    }
    for (const name of stale) problems.push(`${relativeOut(name)} has no spec`);
    if (problems.length === 0) {
      console.log(`clients/typescript/openapi matches the ${specs.length} committed specs`);
      return 0;
    }
    for (const problem of problems) console.error(problem);
    console.error("error: generated OpenAPI types are out of date; run: make openapi-ts");
    return 1;
  }

  mkdirSync(OUT_DIR, { recursive: true });
  for (const file of expected) writeFileSync(join(OUT_DIR, file.name), file.content);
  for (const name of stale) unlinkSync(join(OUT_DIR, name));
  console.log(
    `wrote ${expected.length} files to ${relativeOut("")} (${specs.map((spec) => spec.service).join(", ")})` +
      (stale.length === 0 ? "" : `; removed ${stale.join(", ")}`),
  );
  return 0;
}

const isMain =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  main().then(
    (status) => {
      process.exitCode = status;
    },
    (error) => {
      console.error(error);
      process.exitCode = 1;
    },
  );
}
